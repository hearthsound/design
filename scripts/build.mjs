#!/usr/bin/env node
/*
 * Builds dist/ from icons/:
 *   dist/icons.svg     one <symbol id="<name>"> per icons/<name>.svg
 *   dist/icons.js      export const iconNames = [...]
 *   dist/icons.d.ts    IconName union plus iconNames
 *
 * The package file name is the manifest name with "/" replaced by "-"
 * (adwaita/play -> adwaita-play.svg -> <symbol id="adwaita-play">).
 * Fails when two icon files produce the same symbol id.
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'icons');
const distDir = join(root, 'dist');

function fail(message) {
  console.error(`build: ${message}`);
  process.exitCode = 1;
}

function innerSvg(source, file) {
  const match = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!match) throw new Error(`${file}: no <svg> root element`);
  const attrs = match[1];
  const viewBox = attrs.match(/\bviewBox="([^"]+)"/);
  return {
    viewBox: viewBox ? viewBox[1] : '0 0 16 16',
    body: match[2].trim(),
  };
}

async function main() {
  const entries = await readdir(iconsDir, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.svg'))
    .map((entry) => entry.name)
    .sort();

  if (files.length === 0) {
    fail('icons/ contains no .svg files');
    return;
  }

  const icons = [];
  const seen = new Map();

  for (const file of files) {
    const name = file.slice(0, -'.svg'.length);
    if (seen.has(name)) {
      fail(`two icons produce the symbol id "${name}": ${seen.get(name)} and ${file}`);
      continue;
    }
    seen.set(name, file);

    const source = await readFile(join(iconsDir, file), 'utf8');
    if (/[^\x00-\x7f]/.test(source)) {
      fail(`${file}: non-ASCII content`);
      continue;
    }
    const { viewBox, body } = innerSvg(source, file);
    if (/<symbol\b/.test(body)) {
      fail(`${file}: contains a <symbol>; icons must be plain <svg> files`);
      continue;
    }
    icons.push({ name, viewBox, body });
  }

  if (process.exitCode) return;

  const sprite = [
    '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">',
    ...icons.map((icon) => `  <symbol id="${icon.name}" viewBox="${icon.viewBox}">${icon.body}</symbol>`),
    '</svg>',
    '',
  ].join('\n');

  const names = icons.map((icon) => icon.name);
  const js = [
    '// Generated by scripts/build.mjs. Do not edit.',
    'export const iconNames = [',
    ...names.map((name) => `  '${name}',`),
    '];',
    '',
  ].join('\n');

  const dts = [
    '// Generated by scripts/build.mjs. Do not edit.',
    'export type IconName =',
    ...names.map((name, index) => `  | '${name}'${index === names.length - 1 ? ';' : ''}`),
    'export declare const iconNames: readonly IconName[];',
    '',
  ].join('\n');

  await mkdir(distDir, { recursive: true });
  await writeFile(join(distDir, 'icons.svg'), sprite, 'utf8');
  await writeFile(join(distDir, 'icons.js'), js, 'utf8');
  await writeFile(join(distDir, 'icons.d.ts'), dts, 'utf8');

  console.log(`build: wrote dist/icons.svg, dist/icons.js and dist/icons.d.ts (${names.length} icons)`);
}

main().catch((error) => {
  console.error(`build: ${error.stack || error.message}`);
  process.exitCode = 1;
});
